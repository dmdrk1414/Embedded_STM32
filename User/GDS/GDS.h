/*
 * GDS.h : 프로젝트 공통 #define 모음
 *
 * 사용 방법
 *   - 값이나 타입을 쓰는 모듈에서 #include "GDS.h"
 *   - 값을 바꿀 때는 이 파일만 고치면 된다.
 *   - 모듈별로 구역을 나누고, 각 값에 단위와 의미를 적는다.
 *
 * 구성
 *   1. #define : 설정값, 상수
 *   2. enum    : 여러 모듈이 함께 쓰는 타입
 */
#ifndef GDS_H
#define GDS_H


/* ########################################################################## */
/* #define                                                                     */
/* ########################################################################## */

/* ========================================================================== */
/* App : Task (task.c)                                                         */
/* ========================================================================== */
#define LED_TOGGLE_10MS        (50u)       /* LED 토글 주기   : 10ms × 50  = 500ms */
#define SLEEP_TIMEOUT_10MS     (500u)      /* 무입력 슬립 시간 : 10ms × 500 = 5초   */

/* ========================================================================== */
/* App : Indicator (indicator.c)                                               */
/*   시작할 때 리셋 원인별 LED 표시 패턴                                       */
/* ========================================================================== */
#define INDICATOR_WAKE_BLINK_MS      (150u)    /* PA0 웨이크업 : 웨이크 횟수만큼, 토글 간격 150ms */
#define INDICATOR_PIN_BLINK_COUNT    (10u)     /* RESET 버튼   : 10번                             */
#define INDICATOR_PIN_BLINK_MS       (50u)     /*               토글 간격 50ms (빠르게)           */
#define INDICATOR_WDG_BLINK_COUNT    (3u)      /* 워치독 리셋  : 3번 (고장 표시)                  */
#define INDICATOR_WDG_BLINK_MS       (100u)    /*               토글 간격 100ms                   */
#define INDICATOR_POWER_ON_MS        (1000u)   /* 전원 ON 등   : 1초 켜기                         */

/* ========================================================================== */
/* Service : Os (scheduler.c)                                                  */
/* ========================================================================== */
#define SCH_PERIOD_10MS_US     (10000u)    /* Task 주기 : 10ms = TIM2 1µs × 10000 */
#define SCH_DELAY_STEP_MS      (10u)       /* Sch_DelayMs() 대기 단위 : 10ms마다 워치독 Refresh */

/* ========================================================================== */
/* Service : EcuM (ecu_state_manager.c)                                        */
/*   백업 레지스터 사용 계획 (각 칸의 의미는 EcuM이 정한다)                   */
/*   - 리셋과 Standby에도 지워지지 않는다. (RM0008 6.1 p.81, 7.1.1 p.90)       */
/* ========================================================================== */
#define ECUM_BKP_WAKE_COUNT    (1u)        /* DR1 : 웨이크업 횟수 (PA0로 깨어난 횟수)  */
#define ECUM_BKP_SLEEP_REQ     (2u)        /* DR2 : 잠들기 요청 메모                   */
#define ECUM_SLEEP_REQ_MAGIC   (0x5A5Au)   /* 잠들기 요청 값 (0이나 우연한 값과 구분) */

/* ========================================================================== */
/* Mcal : Mcu (low_power.c)                                                    */
/* ========================================================================== */
#define LP_BKP_REG_COUNT       (10u)       /* STM32F103C8 백업 레지스터 개수 : DR1 ~ DR10 */


/* ########################################################################## */
/* enum                                                                        */
/* ########################################################################## */

/* ========================================================================== */
/* Mcal : Mcu (reset_reason.c)                                                 */
/*   리셋 원인 종류 : Rst_GetReason()이 돌려주는 값                            */
/*   사용처 : reset_reason.c (판별), ecu_state_manager.c (유지 메모리 처리),  */
/*            indicator.c (원인별 LED 표시)                                    */
/* ========================================================================== */
typedef enum
{
    RST_POWER_ON = 0,       /* 전원 ON          : RCC_CSR.PORRSTF (bit 27)                 */
    RST_STANDBY_WAKE,       /* Standby 복귀      : PWR_CSR.SBF (bit 1), PA0 버튼으로 깨어남 */
    RST_STANDBY_WATCHDOG,   /* Standby 중 워치독 리셋 (잠들기 전 리셋 적용 후에는 원래 발생 안 함) */
    RST_PIN,                /* RESET 버튼        : RCC_CSR.PINRSTF (bit 26), NRST 핀        */
    RST_SOFTWARE,           /* 소프트웨어 리셋   : RCC_CSR.SFTRSTF (bit 28)                 */
    RST_WATCHDOG,           /* 워치독 리셋       : RCC_CSR.IWDGRSTF(29), WWDGRSTF(30)       */
    RST_UNKNOWN             /* 위 어디에도 해당하지 않음                                     */
} Rst_ReasonType;

#endif /* GDS_H */
